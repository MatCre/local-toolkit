namespace Toolkit.Generators;

/// <summary>Writes the C# for one strongly-typed id. Plain string building: no Roslyn APIs needed.</summary>
/// <remarks>
/// Every type name is written with <c>global::</c>, so the generated code means the same thing
/// whatever usings or same-named types the user's project has.
/// </remarks>
internal static class IdSourceRenderer
{
    /// <summary>The parts that differ by backing type.</summary>
    private sealed record Backing(
        string Type, string Parse, string TryParse, string Compare, string Format, string JsonRead, string JsonWrite, string Extras);

    private static Backing For(BackingType type, string name) => type switch
    {
        BackingType.Int => Number("int", "GetInt32"),
        BackingType.Long => Number("long", "GetInt64"),
        BackingType.String => new Backing(
            Type: "string",
            Parse: "s ?? throw new global::System.ArgumentNullException(nameof(s))",
            TryParse: "if (s is not null) { result = new(s); return true; }",
            Compare: "global::System.String.CompareOrdinal(Value, other.Value)",
            Format: "Value ?? \"\"",
            JsonRead: $"reader.GetString() ?? throw new global::System.Text.Json.JsonException(\"{name} can't be null.\")",
            JsonWrite: "writer.WriteStringValue(value.Value)",
            Extras: ""),
        _ => new Backing(
            Type: "global::System.Guid",
            Parse: "global::System.Guid.Parse(s, provider)",
            TryParse: "if (global::System.Guid.TryParse(s, provider, out var value)) { result = new(value); return true; }",
            Compare: "Value.CompareTo(other.Value)",
            Format: "Value.ToString()",
            JsonRead: "reader.GetGuid()",
            JsonWrite: "writer.WriteStringValue(value.Value)",
            Extras: $$"""

                    /// <summary>A new, random id.</summary>
                    public static {{name}} New() => new(global::System.Guid.NewGuid());

                    /// <summary>The all-zero id, the same as <c>default</c>.</summary>
                    public static {{name}} Empty => default;

                """),
    };

    private static Backing Number(string type, string jsonGetter) => new(
        Type: type,
        Parse: $"{type}.Parse(s, provider)",
        TryParse: $"if ({type}.TryParse(s, provider, out var value)) {{ result = new(value); return true; }}",
        Compare: "Value.CompareTo(other.Value)",
        Format: "Value.ToString(global::System.Globalization.CultureInfo.InvariantCulture)",
        JsonRead: $"reader.{jsonGetter}()",
        JsonWrite: "writer.WriteNumberValue(value.Value)",
        Extras: "");

    public static string Render(IdModel model)
    {
        var name = model.Name;
        var b = For(model.Backing, name);
        var namespaceLine = model.Namespace is null ? "" : $"namespace {model.Namespace};\n\n";

        return $$"""
            // <auto-generated>
            //   Generated by Toolkit.Generators from [StronglyTypedId] on {{name}}.
            //   Changes here are lost on the next build: change the declaration instead.
            // </auto-generated>
            #nullable enable

            {{namespaceLine}}/// <summary>A strongly-typed id wrapping a <c>{{b.Type.Replace("global::", "")}}</c>.</summary>
            [global::System.Text.Json.Serialization.JsonConverter(typeof({{name}}.JsonConverter))]
            partial record struct {{name}}({{b.Type}} Value) : global::System.IComparable<{{name}}>, global::System.IParsable<{{name}}>
            {
                /// <summary>The wrapped value. Read-only: an id never changes after it's created.</summary>
                public {{b.Type}} Value { get; } = Value;
            {{b.Extras}}
                public int CompareTo({{name}} other) => {{b.Compare}};

                public override string ToString() => {{b.Format}};

                public static {{name}} Parse(string s, global::System.IFormatProvider? provider = null) => new({{b.Parse}});

                public static bool TryParse([global::System.Diagnostics.CodeAnalysis.NotNullWhen(true)] string? s, global::System.IFormatProvider? provider, out {{name}} result)
                {
                    {{b.TryParse}}
                    result = default;
                    return false;
                }

                /// <summary>The overload minimal APIs look for when binding a route or query value.</summary>
                public static bool TryParse([global::System.Diagnostics.CodeAnalysis.NotNullWhen(true)] string? s, out {{name}} result) =>
                    TryParse(s, null, out result);

                /// <summary>Reads and writes the id as its plain value, e.g. <c>"3f2a…"</c> rather than <c>{"Value":"3f2a…"}</c>.</summary>
                public sealed class JsonConverter : global::System.Text.Json.Serialization.JsonConverter<{{name}}>
                {
                    public override {{name}} Read(ref global::System.Text.Json.Utf8JsonReader reader, global::System.Type typeToConvert, global::System.Text.Json.JsonSerializerOptions options) =>
                        new({{b.JsonRead}});

                    public override void Write(global::System.Text.Json.Utf8JsonWriter writer, {{name}} value, global::System.Text.Json.JsonSerializerOptions options) =>
                        {{b.JsonWrite}};
                }
            }

            """;
    }
}
